#pragma region Frame Update
// Executes the basic game loop.
void Game::Tick()
{
    m_timer.Tick([]()
    {
    });

    PollInput();

    m_accumulator = std::min(m_accumulator + m_timer.GetElapsedSeconds(), kMaxAccumulator);

    const auto start = std::chrono::steady_clock::now();
    for (int ticks = 0; m_accumulator >= kFixedStep && ticks < kMaxTicksPerFrame; ++ticks)
    {
        const double spent = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
        if (spent + m_core.RenderCostEstimate() > kFrameBudget)
        {
            break;
        }

        Update(kFixedStep);
        m_accumulator -= kFixedStep;
    }

    Render();
}

// Updates the world.
void Game::Update(double elapsedSeconds)
{
    PIXBeginEvent(PIX_COLOR_DEFAULT, L"Update");

    m_core.Tick(elapsedSeconds, m_input.Commands());

    PIXEndEvent();
}

// Samples devices once per frame and builds the frame's command set.
void Game::PollInput()
{
    m_input.Advance(m_devices.Sample());
}

